package com.tikit.rag.worker;

import com.tikit.rag.chunking.RagChunkSplitter;
import com.tikit.rag.config.RagChunkingProperties;
import com.tikit.rag.config.RagIndexingProperties;
import com.tikit.rag.embedding.OllamaEmbeddingClient;
import com.tikit.rag.entity.*;
import com.tikit.rag.repository.*;
import org.junit.jupiter.api.*;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.context.annotation.Import;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.orm.jpa.JpaTransactionManager;
import org.springframework.test.annotation.DirtiesContext;
import org.springframework.test.context.junit.jupiter.SpringJUnitConfig;
import org.springframework.test.util.ReflectionTestUtils;
import org.springframework.transaction.support.TransactionSynchronizationManager;
import org.springframework.transaction.support.TransactionTemplate;

import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.Executors;
import java.util.concurrent.TimeUnit;

import static org.assertj.core.api.Assertions.*;
import static org.mockito.Mockito.*;

/** 실제 pgvector 타입과 JPA/JDBC의 공동 커밋·롤백을 검증한다. */
@Tag("local-db")
@SpringJUnitConfig(RagIndexCompletionIntegrationTest.Config.class)
@DirtiesContext(classMode = DirtiesContext.ClassMode.AFTER_CLASS)
class RagIndexCompletionIntegrationTest {
    @Autowired RagIndexJobService jobs;
    @Autowired RagIndexCompletionService completion;
    @Autowired RagIndexProcessor processor;
    @Autowired RagIndexJobRepository jobRepository;
    @Autowired RagDocumentRepository documents;
    @Autowired RagDocumentVersionRepository versions;
    @Autowired RagChunkSplitter splitter;
    @Autowired OllamaEmbeddingClient embedding;
    @Autowired JdbcTemplate jdbc;
    @Autowired JpaTransactionManager transactionManager;

    @BeforeEach
    void prepare() {
        // 이미 설치된 pgvector만 사용하며 공유 스키마나 확장을 생성·변경하지 않는다.
        String extensionSchema = jdbc.queryForObject("""
                select n.nspname from pg_extension e join pg_namespace n on n.oid = e.extnamespace
                where e.extname = 'vector'
                """, String.class);
        String vectorType = "\"" + extensionSchema.replace("\"", "\"\"") + "\".vector(4096)";
        jdbc.execute("""
                create table if not exists rag_chunks (
                    id bigint generated by default as identity primary key,
                    document_id bigint not null, document_version integer not null,
                    chunk_order integer not null check (chunk_order >= 0), content text not null,
                    embedding %s not null, created_at timestamptz not null default current_timestamp,
                    unique (document_id, document_version, chunk_order),
                    foreign key (document_id, document_version) references rag_document_versions(document_id, version)
                )
                """.formatted(vectorType));
        jdbc.update("delete from rag_chunks");
        jobRepository.deleteAll();
        versions.deleteAll();
        documents.deleteAll();
        reset(embedding);
        when(embedding.embed(anyList())).thenAnswer(call -> {
            assertThat(TransactionSynchronizationManager.isActualTransactionActive()).isFalse();
            List<String> texts = call.getArgument(0);
            return vectors(texts.size());
        });
    }

    @Test
    void savesVectorsAndActivatesOnlyAfterAllChunksAreStored() {
        var task = claim("가나다라마바", false);
        processor.process(task);
        assertThat(jdbc.queryForList("select content from rag_chunks order by chunk_order", String.class))
                .containsExactly("가나다", "라마바");
        assertThat(jdbc.queryForList("select embedding::text from rag_chunks order by chunk_order", String.class))
                .allSatisfy(value -> {
                    String[] coordinates = value.substring(1, value.length() - 1).split(",");
                    assertThat(coordinates).hasSize(4096);
                    assertThat(Float.parseFloat(coordinates[0])).isEqualTo(1.0f);
                    assertThat(Float.parseFloat(coordinates[4095])).isEqualTo(0.0f);
                });
        var job = jobRepository.findById(task.jobId()).orElseThrow();
        assertThat(job.getStatus()).isEqualTo(RagIndexJobStatus.SUCCEEDED);
        assertThat(job.getCompletedAt()).isNotNull();
        assertThat(job.getLeaseOwner()).isNull();
        assertThat(job.getFailureCode()).isNull();
        assertThat(version(task).getIndexStatus()).isEqualTo(RagIndexStatus.READY);
        assertThat(documents.findById(task.documentId()).orElseThrow().getActiveVersion()).isEqualTo(1);
    }

    @Test
    void duplicateConcurrentCompletionDoesNotReplaceOrDuplicateChunks() throws Exception {
        var task = claim("가나다라마바", false);
        var texts = splitter.split(task.content());
        var vectors = vectors(texts.size());
        var start = new CountDownLatch(1);
        try (var executor = Executors.newFixedThreadPool(2)) {
            var first = executor.submit(() -> { start.await(); completion.complete(task, texts, vectors); return null; });
            var second = executor.submit(() -> { start.await(); completion.complete(task, texts, vectors); return null; });
            start.countDown();
            first.get(15, TimeUnit.SECONDS);
            second.get(15, TimeUnit.SECONDS);
        }
        var ids = jdbc.queryForList("select id from rag_chunks order by id", Long.class);
        completion.complete(task, texts, vectors);
        assertThat(jdbc.queryForList("select id from rag_chunks order by id", Long.class)).containsExactlyElementsOf(ids);
        assertThat(ids).hasSize(2);
    }

    @Test
    void rejectsCompletionByAnotherWorker() {
        var task = claim("가나다", false);
        var other = new RagIndexTask(task.jobId(), task.documentId(), task.documentVersion(), task.content(),
                task.embeddingModel(), task.embeddingDimensions(), "another-worker");
        assertThatThrownBy(() -> completion.complete(other, splitter.split(task.content()), vectors(1)))
                .isInstanceOf(IllegalStateException.class);
        assertNotCompleted(task, null);
    }

    @Test
    void invalidDimensionsDoNotLeaveSuccessfulState() {
        var task = claim("가나다", false);
        assertThatThrownBy(() -> completion.complete(task, splitter.split(task.content()), List.of(List.of(1.0))))
                .isInstanceOf(IllegalArgumentException.class);
        assertNotCompleted(task, null);
    }

    @Test
    void laterChunkFailureRollsBackAllChunksAndWorkerPreservesPreviousActiveVersion() {
        jdbc.execute("alter table rag_chunks add constraint reject_second_chunk check (content <> '실패문')");
        try {
            Long id = createJob("정상문실패문", true);
            new RagIndexWorker(jobs, processor, new RagIndexingProperties(true, 10, 5000)).poll();
            var job = jobRepository.findById(id).orElseThrow();
            assertThat(jdbc.queryForObject("select count(*) from rag_chunks", Long.class)).isZero();
            assertThat(job.getStatus()).isEqualTo(RagIndexJobStatus.FAILED);
            assertThat(job.getFailureCode()).isEqualTo("INDEX_PROCESSING_FAILED");
            assertThat(versions.findById(new RagDocumentVersionId(job.getDocumentId(), 2)).orElseThrow().getIndexStatus())
                    .isEqualTo(RagIndexStatus.FAILED);
            assertThat(documents.findById(job.getDocumentId()).orElseThrow().getActiveVersion()).isEqualTo(1);
        } finally {
            jdbc.execute("alter table rag_chunks drop constraint reject_second_chunk");
        }
    }

    @Test
    void failureToFlushSuccessStateAlsoRollsBackJdbcInserts() {
        var task = claim("가나다라마바", false);
        jdbc.execute("alter table rag_index_jobs add constraint reject_success check (status <> 'SUCCEEDED')");
        try {
            assertThatThrownBy(() -> processor.process(task)).isInstanceOf(RuntimeException.class);
            assertNotCompleted(task, null);
        } finally {
            jdbc.execute("alter table rag_index_jobs drop constraint reject_success");
        }
    }

    @Test
    void newVersionReplacesActiveVersionAfterSuccess() {
        var task = claim("가나다", true);
        processor.process(task);
        assertThat(version(task).getIndexStatus()).isEqualTo(RagIndexStatus.READY);
        assertThat(documents.findById(task.documentId()).orElseThrow().getActiveVersion()).isEqualTo(2);
    }

    @Test
    void olderVersionFinishingLateDoesNotReplaceNewerActiveVersion() {
        var task = claim("가나다", true);
        new TransactionTemplate(transactionManager).executeWithoutResult(status -> {
            var document = documents.findById(task.documentId()).orElseThrow();
            ReflectionTestUtils.setField(document, "latestVersion", 3);
            var latest = RagDocumentVersion.createFirstVersion(document.getId(), "최신 정책", "최신 본문", "c".repeat(64), 42L);
            ReflectionTestUtils.setField(latest, "id", new RagDocumentVersionId(document.getId(), 3));
            latest.startIndexing("Qwen/Qwen3-Embedding-8B", 4096);
            latest.completeIndexing();
            versions.saveAndFlush(latest);
            document.activateVersion(3);
        });
        processor.process(task);
        assertThat(version(task).getIndexStatus()).isEqualTo(RagIndexStatus.READY);
        assertThat(documents.findById(task.documentId()).orElseThrow().getActiveVersion()).isEqualTo(3);
    }

    @Test
    void suspendsCallerTransactionWhileCallingEmbeddingModel() {
        var task = claim("가나다", false);
        new TransactionTemplate(transactionManager).executeWithoutResult(status -> processor.process(task));
        assertThat(jobRepository.findById(task.jobId()).orElseThrow().getStatus()).isEqualTo(RagIndexJobStatus.SUCCEEDED);
        verify(embedding).embed(List.of("가나다"));
    }

    private void assertNotCompleted(RagIndexTask task, Integer active) {
        assertThat(jdbc.queryForObject("select count(*) from rag_chunks", Long.class)).isZero();
        assertThat(jobRepository.findById(task.jobId()).orElseThrow().getStatus()).isEqualTo(RagIndexJobStatus.RUNNING);
        assertThat(version(task).getIndexStatus()).isEqualTo(RagIndexStatus.RUNNING);
        assertThat(documents.findById(task.documentId()).orElseThrow().getActiveVersion()).isEqualTo(active);
    }

    private RagDocumentVersion version(RagIndexTask task) {
        return versions.findById(new RagDocumentVersionId(task.documentId(), task.documentVersion())).orElseThrow();
    }

    private RagIndexTask claim(String content, boolean previousActive) {
        return jobs.claim(createJob(content, previousActive), "worker").orElseThrow();
    }

    private Long createJob(String content, boolean previousActive) {
        return new TransactionTemplate(transactionManager).execute(status -> {
            var document = documents.saveAndFlush(RagDocument.createPolicy(42L));
            if (previousActive) {
                var previous = RagDocumentVersion.createFirstVersion(document.getId(), "기존 정책", "이전 본문", "b".repeat(64), 42L);
                previous.startIndexing("Qwen/Qwen3-Embedding-8B", 4096);
                previous.completeIndexing();
                versions.saveAndFlush(previous);
                document.activateVersion(1);
                ReflectionTestUtils.setField(document, "latestVersion", 2);
            }
            int number = previousActive ? 2 : 1;
            var version = RagDocumentVersion.createFirstVersion(document.getId(), "정책", content, "a".repeat(64), 42L);
            ReflectionTestUtils.setField(version, "id", new RagDocumentVersionId(document.getId(), number));
            versions.saveAndFlush(version);
            return jobRepository.saveAndFlush(RagIndexJob.createQueued(document.getId(), number, 42L)).getId();
        });
    }

    private static List<List<Double>> vectors(int count) {
        var vector = new ArrayList<>(Collections.nCopies(4096, 0.0));
        vector.set(0, 1.0);
        return Collections.nCopies(count, List.copyOf(vector));
    }

    @Configuration
    @Import({RagIndexJobServiceIntegrationTest.Config.class, RagChunkRepository.class,
            RagIndexCompletionService.class, DefaultRagIndexProcessor.class})
    static class Config {
        @Bean RagChunkSplitter splitter() { return new RagChunkSplitter(new RagChunkingProperties(3, 0)); }
        @Bean OllamaEmbeddingClient embeddingClient() { return mock(OllamaEmbeddingClient.class); }
    }
}
